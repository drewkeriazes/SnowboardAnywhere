import type { Pack } from '../pack/Pack';
import type { Settings } from '../ui/Settings';

/**
 * FEAT-128: the main menu's backdrop shots, hand-picked so the place is recognisable. The menu runs inside the
 * session: the eye camera sits on the shot and drifts slowly while ghosts ride lines through it. Each shot ships
 * with a still rendered from the same pose (`game/public/attract/<slug>/<id>.jpg`, `tools/shoot_attract.mjs`),
 * shown while the session loads. FEAT-181: the shots are data, `game/public/attract/<slug>/shots.json` (the menu
 * uses the first), written by the eye camera's Shift+P with ?debug (`/__attract/shot`, `tools/ghost_lines.mjs`).
 * FEAT-175: a resort without hand-made shots uses the pack's own, generated by MapPacker's gen_content.py into
 * `packs/<slug>/attract/` (same files, `index.json` being the resort's entry), with the still and ghost takes from
 * `tools/auto_attract.mjs`; `loadAttractManifest` folds them in (`dir`), so everything below reads both alike.
 */
export interface AttractShot {
  id: string;
  /** why the shot is where it is (for people; the game doesn't read it) */
  note?: string;
  /** pack metres, heading in degrees clockwise from north, pitch in degrees (+ up), vertical fov, eye height above the snow (m) */
  x: number; y: number; h: number; pitch: number; fov: number; eye: number;
  /** the big title (the place in the shot) and the line above it */
  place: string; region: string;
  /** the place's elevation (m) and where it is measured, from a source named in the table (resort numbers are counted from the pack) */
  elev?: { m: number; where: string };
  /** the drift: metres of dolly along the view and degrees of pan, over one cycle of `period` seconds */
  dolly: number; pan: number; period: number;
  /** FEAT-177: the conditions the menu draws the shot in (and the still is rendered in), whatever the player's settings */
  conditions: ShotConditions;
}

/**
 * FEAT-177: what the shot looks like, as the Settings fields that change the picture: the weather, the sun
 * (a fixed hour on the 15th of `month`, or the pack's own sun), the new snow and the snow day, the valley fog,
 * and where the clouds start (seconds of wind, Clouds.ts). The menu draws these while it is up (until the
 * player picks a condition in its Settings) and `tools/shoot_attract.mjs` renders the still with the same.
 */
export type ShotConditions = Pick<Settings, 'clouds' | 'month' | 'snowDay' | 'valleyFog'> & {
  timeOfDay: 'pack' | number; newSnow: NonNullable<Settings['newSnow']>; cloudTime: number;
};
/** the shot conditions for a resort without a hand-picked shot */
export const DEFAULT_CONDITIONS: ShotConditions = { clouds: 'few', timeOfDay: 'pack', month: 2, newSnow: 'none', snowDay: 'mid', valleyFog: false, cloudTime: 0 };
/** the Settings fields a shot's conditions override (a pick of any of them in the menu's Settings ends the override) */
export const CONDITION_FIELDS = ['clouds', 'timeOfDay', 'month', 'newSnow', 'snowDay', 'valleyFog'] as const;

/**
 * FEAT-181: a resort's shots (`attract/<slug>/shots.json`), asked for only when the manifest says it has some
 * (`shots: true`), so a resort without one requests nothing and nothing 404s; [] then.
 */
export async function loadAttractShots(base: string, slug: string, man: AttractManifest): Promise<AttractShot[]> {
  if (!man[slug]?.shots) return [];
  try {
    const r = await fetch(`${attractDir(base, slug, man)}shots.json`, { cache: 'no-cache' });
    if (!r.ok) return [];
    const shots = await r.json() as AttractShot[];
    return Array.isArray(shots) ? shots.filter((s) => s && typeof s.id === 'string' && Number.isFinite(s.x) && Number.isFinite(s.y)) : [];
  } catch { return []; }
}

/**
 * `game/public/attract/index.json`: per resort, the shot ids with a rendered still, the ghost take files, and
 * (FEAT-177) each still's look key from `tools/shoot_attract.mjs`: `code`, a hash of the source files that
 * change the picture and of the resort's `shots.json` (`tools/attract_look.mjs`, checked in CI), and `pack`, the
 * pack's `meta.build` it was rendered from (checked here: a still from another build of the pack is never shown).
 * FEAT-181: `shots` says the resort has `shots.json`; `shotGhosts` lists, per shot, the takes `tools/ghost_lines.mjs` made for it (also in `ghosts`): a new
 * shot replaces the old one and its generated takes with it; recorded `take-*` files are never in it.
 */
export interface StillLook { code: string; pack: string }
/**
 * One resort's entry. FEAT-175: `generated` marks the pack's own (gen_content.py), and `dir`, set by
 * `loadAttractManifest` (never in a file), is the URL folder of its files when they are not `attract/<slug>/`.
 */
export interface AttractEntry { shots?: boolean; stills?: string[]; ghosts?: string[]; looks?: Record<string, StillLook>; shotGhosts?: Record<string, string[]>; generated?: boolean; dir?: string }
export type AttractManifest = Record<string, AttractEntry>;

/** The URL folder (ending in /) of a resort's shots, stills and takes. */
export function attractDir(base: string, slug: string, man: AttractManifest): string {
  return man[slug]?.dir ?? `${base}attract/${slug}/`;
}

/** The shipped still for a shot, or '' when there is none or it was rendered from another build of the pack. */
export function shippedStill(base: string, man: AttractManifest, pack: Pack, shotId: string): string {
  const mine = man[pack.meta.slug];
  if (!mine?.stills?.includes(shotId)) return '';
  const look = mine.looks?.[shotId];
  if (!look || look.pack !== (pack.meta.build ?? '')) return '';
  return `${attractDir(base, pack.meta.slug, man)}${shotId}.jpg`;
}
/**
 * The manifest ({} when missing, so nothing else is requested and nothing 404s). FEAT-175: with `pack`, a resort the
 * game has no hand-made entry for takes the pack's own `attract/index.json`, asked for only when `meta.attract` says
 * the pack has one; its files are then read from the pack (`dir`). The game's hand-made entry always wins.
 */
export async function loadAttractManifest(base: string, pack?: Pack): Promise<AttractManifest> {
  let man: AttractManifest = {};
  try { const r = await fetch(`${base}attract/index.json`, { cache: 'no-cache' }); if (r.ok) man = await r.json() as AttractManifest; } catch { /* none */ }
  const slug = pack?.meta.slug;
  if (pack && slug && !man[slug] && pack.meta.attract) {
    try {
      const r = await fetch(`${pack.baseUrl}/attract/index.json`, { cache: 'no-cache' });
      if (r.ok) man[slug] = { ...(await r.json() as AttractEntry), dir: `${pack.baseUrl}/attract/` };
    } catch { /* the pack's menu is optional */ }
  }
  return man;
}

/** The shot for a resort: its first hand-picked one (`loadAttractShots`), else the start looking downhill from 15 m up. */
export function attractShot(pack: Pack, start: { x: number; y: number; heading: number }, shots: AttractShot[]): AttractShot {
  const s = shots[0];
  if (s) return s;
  return {
    id: 'start', x: start.x, y: start.y, h: start.heading * 180 / Math.PI, pitch: -10, fov: 55, eye: 15,
    place: pack.meta.name, region: '', dolly: 4, pan: 1.5, period: 26, conditions: DEFAULT_CONDITIONS,
  };
}

/** The pose at time t: a slow dolly along the view and a pan, eased in and out (back and forth over `period`). */
export function shotPose(s: AttractShot, t: number): { x: number; y: number; h: number; pitch: number; fov: number; eye: number } {
  const k = 0.5 - 0.5 * Math.cos((t / s.period) * Math.PI * 2); // 0 .. 1 .. 0
  const hr = s.h * Math.PI / 180;
  return { x: s.x + Math.sin(hr) * s.dolly * k, y: s.y + Math.cos(hr) * s.dolly * k, h: s.h + s.pan * (k - 0.5), pitch: s.pitch, fov: s.fov, eye: s.eye };
}

/** Resort numbers counted from the pack (never typed): named runs, lifts, and the lift-served top and vertical. */
export function resortNumbers(pack: Pack): { runs: number; lifts: number; top: number | null; vertical: number | null } {
  const f = pack.features;
  const runs = new Set(f.runs.filter((r) => r.name && !r.area).map((r) => r.name)).size;
  const zs = f.lifts.flatMap((l) => l.stations.map((s) => s[2])).filter((z) => Number.isFinite(z));
  const top = zs.length ? Math.max(...zs) : null, bottom = zs.length ? Math.min(...zs) : null;
  return { runs, lifts: f.lifts.length, top, vertical: top !== null && bottom !== null ? top - bottom : null };
}
